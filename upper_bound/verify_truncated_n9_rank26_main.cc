using IntegerTensor = std::array<std::array<std::array<int64_t, kN>, kN>, kN>;

void Verify() {
  CHECK_EQ(kScheme.size(), kRank);
  IntegerTensor reconstructed{};
  for (const RankOneTerm &term : kScheme) {
    for (std::size_t i = 0; i < kN; ++i) {
      for (std::size_t j = 0; j < kN; ++j) {
        for (std::size_t k = 0; k < kN; ++k) {
          reconstructed[i][j][k] += term.a[i] * term.b[j] * term.c[k];
        }
      }
    }
  }

  for (std::size_t i = 0; i < kN; ++i) {
    for (std::size_t j = 0; j < kN; ++j) {
      for (std::size_t k = 0; k < kN; ++k) {
        const int64_t expected = i + j < kN && k == i + j ? 1 : 0;
        CHECK_EQ(reconstructed[i][j][k], expected)
            << "coefficient mismatch at (a" << i << ", b" << j << ", c" << k
            << ")";
      }
    }
  }
}

